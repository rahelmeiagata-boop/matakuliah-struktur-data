#include <stdio.h>

int main() {
    int x = 10;
    int y = 5;

    printf("Equal to (==): %d\n", x == y);
    printf("Not equal (!=): %d\n", x != y);
    printf("Greater than (>): %d\n", x > y);
    printf("Less than (<): %d\n", x < y);
    printf("Greater than or equal (>=): %d\n", x >= y);
    printf("Less than or equal (<=): %d\n", x <= y);

    return 0;
}